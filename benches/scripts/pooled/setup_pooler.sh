#!/usr/bin/env bash
# benches/scripts/pooled/setup_pooler.sh — install + configure PgBouncer
# in TRANSACTION pooling, pointed at the DB tier.
#
# Runs ON the pooler tier (its own instance in the real rig; this host in
# the collapsed diagnostic). Parameterised through common.sh env plus:
#
#   POOL_MODE          transaction|session|statement (default transaction)
#   DEFAULT_POOL_SIZE  backends the pooler opens to the DB (= DB load)   [50]
#   MAX_CLIENT_CONN    logical client ceiling                           [5000]
#   SERVER_LIFETIME    seconds before a server conn is recycled          [600]
#   RESERVE_POOL       extra backends under burst                        [10]
#   PGB_PREFIX         where PgBouncer config/pid/log live   [$HOME/s0/pgbouncer]
#   PGB_AUTH_USER      role to auth as (trust/plain for the bench)   [$PGUSER]
#
# PgBouncer must be reachable; on Debian: `sudo apt-get install pgbouncer`
# (this script finds the binary; it does NOT sudo apt for you).
#
# Usage:
#   DEFAULT_POOL_SIZE=50 MAX_CLIENT_CONN=5000 bash setup_pooler.sh start
#   bash setup_pooler.sh stop
#   bash setup_pooler.sh reload

set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=common.sh
source "${HERE}/common.sh"

POOL_MODE="${POOL_MODE:-transaction}"
DEFAULT_POOL_SIZE="${DEFAULT_POOL_SIZE:-50}"
MAX_CLIENT_CONN="${MAX_CLIENT_CONN:-5000}"
SERVER_LIFETIME="${SERVER_LIFETIME:-600}"
RESERVE_POOL="${RESERVE_POOL:-10}"
PGB_PREFIX="${PGB_PREFIX:-$HOME/s0/pgbouncer}"
PGB_AUTH_USER="${PGB_AUTH_USER:-$PGUSER}"

PGBOUNCER_BIN="${PGBOUNCER_BIN:-$(command -v pgbouncer || echo /usr/sbin/pgbouncer)}"
[ -x "${PGBOUNCER_BIN}" ] || { echo "pgbouncer not found (${PGBOUNCER_BIN}); apt-get install pgbouncer" >&2; exit 1; }

INI="${PGB_PREFIX}/pgbouncer.ini"
USERLIST="${PGB_PREFIX}/userlist.txt"
PIDFILE="${PGB_PREFIX}/pgbouncer.pid"
LOGFILE="${PGB_PREFIX}/pgbouncer.log"

write_config() {
    mkdir -p "${PGB_PREFIX}"
    # userlist: for the bench we trust the local operator role. On the real
    # rig use SCRAM + a hashed userlist, never trust across the network.
    cat >"${USERLIST}" <<EOF
"${PGB_AUTH_USER}" ""
EOF
    cat >"${INI}" <<EOF
;; PgBouncer config generated by setup_pooler.sh — transaction pooling.
[databases]
${PGDATABASE} = host=${DB_HOST} port=${DB_PORT} dbname=${PGDATABASE}

[pgbouncer]
listen_addr = *
listen_port = ${POOLER_PORT}
auth_type = trust
auth_file = ${USERLIST}
pool_mode = ${POOL_MODE}
default_pool_size = ${DEFAULT_POOL_SIZE}
reserve_pool_size = ${RESERVE_POOL}
reserve_pool_timeout = 3
max_client_conn = ${MAX_CLIENT_CONN}
server_lifetime = ${SERVER_LIFETIME}
server_idle_timeout = 120
; pass search_path through so turbovec operators resolve (transaction mode
; drops SET, so we also rely on schema-qualified SQL in run_load.sh).
ignore_startup_parameters = extra_float_digits,options,search_path
pidfile = ${PIDFILE}
logfile = ${LOGFILE}
admin_users = ${PGB_AUTH_USER}
stats_users = ${PGB_AUTH_USER}
; expose pool stats on the admin console (psql -p PORT pgbouncer)
EOF
    log "wrote ${INI} (pool_mode=${POOL_MODE} default_pool_size=${DEFAULT_POOL_SIZE} max_client_conn=${MAX_CLIENT_CONN} server_lifetime=${SERVER_LIFETIME})"
}

start() {
    write_config
    if [ -f "${PIDFILE}" ] && kill -0 "$(cat "${PIDFILE}")" 2>/dev/null; then
        log "pgbouncer already running (pid $(cat "${PIDFILE}")); reloading"
        kill -HUP "$(cat "${PIDFILE}")"; return 0
    fi
    log "starting pgbouncer -> ${POOLER_HOST}:${POOLER_PORT}"
    "${PGBOUNCER_BIN}" -d "${INI}"
    sleep 1
    # verify we can reach the pooler admin console
    "${PSQL}" -h "${POOLER_HOST}" -p "${POOLER_PORT}" -U "${PGB_AUTH_USER}" \
        -d pgbouncer -tAc "SHOW version;" >&2 || {
        echo "pgbouncer did not come up; see ${LOGFILE}" >&2; tail -5 "${LOGFILE}" >&2; exit 1; }
    log "pgbouncer up"
}

stop() {
    [ -f "${PIDFILE}" ] || { log "no pidfile ${PIDFILE}"; return 0; }
    local pid; pid="$(cat "${PIDFILE}")"
    log "stopping pgbouncer pid ${pid}"
    kill "${pid}" 2>/dev/null || true
}

reload() { [ -f "${PIDFILE}" ] && kill -HUP "$(cat "${PIDFILE}")"; }

case "${1:-start}" in
    start) start;;
    stop) stop;;
    reload) reload;;
    config) write_config;;
    *) echo "usage: $0 {start|stop|reload|config}" >&2; exit 2;;
esac
