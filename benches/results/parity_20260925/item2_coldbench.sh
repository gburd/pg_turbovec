#!/usr/bin/env bash
# item2_coldbench.sh — cold-scan latency benchmark for pg_turbovec parity gap Item 2.
#
# TARGET: Ubuntu 24.04, PostgreSQL 16, pg_turbovec v2.10.2, c7i.4xlarge (16 vCPU, AVX2).
# AVX2 is REQUIRED — per AGENTS.md, turbovec latency is only meaningful on an AVX2+ host
# (meh/rv take the ~1000x-slower scalar fallback and must NEVER be used for latency).
#
# ENGINE SELECTION IS BY COLUMN + OPERATOR, NOT A GUC. turbovec opclasses are over the
# DISTINCT type turbovec.vector, so the two engines CANNOT share a column:
#   items.v  vector(1024)      -> pgvector HNSW, queried `v <=> (pgvector query)`
#   items.tv turbovec.vector   -> turbovec index, queried `tv OPERATOR(turbovec.<=>) (tv query)`
# Both engines rank by COSINE so the head-to-head is comparable (HNSW vector_cosine_ops;
# turbovec vec_cosine_ops + OPERATOR(turbovec.<=>)). There is NO turbovec.enabled toggle;
# each arm queries its own column, and we force the index with enable_seqscan=off AND
# assert the EXPLAIN plan actually used the intended index (else the trial is flagged).
#
# WHAT "COLD SCAN" MEANS HERE: the FIRST distance query in a FRESH backend (new psql
# connection). That first query pays the full per-backend cache-fill (read_full_consistent
# + pack::repack prepare()). We measure it across three regimes and compare to pgvector HNSW:
#
#   R1  cold-backend + true-cold-disk   : drop_caches before the trial (upper bound, disk-bound)
#   R2  cold-backend + warm-OS-cache    : no drop_caches (THE POOLED/SERVERLESS REALITY)
#   R3  warm-backend                    : 2nd/3rd query in the SAME backend (lower bound)
#
# The R1-R2 gap = how much is disk (mmap-relevant, but mmap is off the table in v2.10.2).
# The R2-R3 gap = how much is per-backend compute (read_chain copy + pack::repack) — the
# term the re-scoped design (§3a parallel repack) could attack. This split is the DECISION.
#
# Output: /tmp/item2_results.csv  (engine,regime,trial,latency_ms) + a p50/p95 summary.
#
# DO NOT RUN in this session — this is the runnable artifact for the AVX2 host.

set -euo pipefail

# ---------------------------------------------------------------------------
# Config (override via env)
# ---------------------------------------------------------------------------
PGDB="${PGDB:-coldbench}"
PGUSER="${PGUSER:-$(whoami)}"
PGHOST="${PGHOST:-/var/run/postgresql}"   # unix socket dir; local peer/trust assumed
PGPORT="${PGPORT:-5432}"
N_ROWS="${N_ROWS:-1000000}"       # ~1M vectors
DIM="${DIM:-1024}"                # 1024-d
BIT_WIDTH="${BIT_WIDTH:-4}"       # 4-bit turbovec
K="${K:-10}"                      # LIMIT 10
TRIALS="${TRIALS:-30}"            # fresh-backend trials per regime
HNSW_M="${HNSW_M:-16}"
HNSW_EF_CONSTRUCTION="${HNSW_EF_CONSTRUCTION:-64}"
HNSW_EF_SEARCH="${HNSW_EF_SEARCH:-100}"
OUT="${OUT:-/tmp/item2_results.csv}"
SEED="${SEED:-42}"

PSQL="psql -h ${PGHOST} -p ${PGPORT} -U ${PGUSER} -d ${PGDB} -v ON_ERROR_STOP=1 -qAtX"
PSQL_ADMIN="psql -h ${PGHOST} -p ${PGPORT} -U ${PGUSER} -d postgres -v ON_ERROR_STOP=1 -qAtX"

# Index names — used both to build and to ASSERT the plan picked the right one.
TV_INDEX="items_tv"
HNSW_INDEX="items_hnsw"

echo "=== item2_coldbench: N=${N_ROWS} dim=${DIM} bit_width=${BIT_WIDTH} k=${K} trials=${TRIALS} ==="

# ---------------------------------------------------------------------------
# Preflight: AVX2 present? (latency numbers are garbage without it)
# ---------------------------------------------------------------------------
if grep -qw avx2 /proc/cpuinfo; then
  echo "[preflight] AVX2 present — OK for latency."
else
  echo "[preflight] !!! NO AVX2 — turbovec will take the scalar fallback (~1000x slower)."
  echo "[preflight] !!! Latency numbers from this host are INVALID per AGENTS.md. Aborting."
  exit 2
fi

# drop_caches needs root; test once so R1 can warn cleanly if it can't.
CAN_DROP_CACHES=0
if sudo -n sh -c 'echo 1 > /proc/sys/vm/drop_caches' 2>/dev/null; then
  CAN_DROP_CACHES=1
  echo "[preflight] drop_caches OK (passwordless sudo) — R1 (true-cold-disk) will run."
else
  echo "[preflight] WARNING: no passwordless sudo for drop_caches — R1 will be SKIPPED."
fi

# ---------------------------------------------------------------------------
# Schema + data. TWO vector columns, because turbovec opclasses are over the
# DISTINCT type turbovec.vector and CANNOT index a pgvector `vector` column:
#   v  vector(1024)     -> pgvector HNSW
#   tv turbovec.vector  -> pg_turbovec (populated by UPDATE ... ::real[]::turbovec.vector)
# turbovec.vector has no binary recv; here the corpus is generated by INSERT...SELECT
# (no binary COPY), so a plain post-insert UPDATE is fine.
# ---------------------------------------------------------------------------
$PSQL_ADMIN -c "DROP DATABASE IF EXISTS ${PGDB};"
$PSQL_ADMIN -c "CREATE DATABASE ${PGDB};"
$PSQL -c "CREATE EXTENSION IF NOT EXISTS vector;"        # pgvector
$PSQL -c "CREATE EXTENSION IF NOT EXISTS pg_turbovec;"

echo "[data] generating ${N_ROWS} x ${DIM}-d random vectors (server-side, seed ${SEED})..."
# random_normal is PG16+. setseed makes the corpus + queries reproducible.
$PSQL <<SQL
SELECT setseed(${SEED} / 2147483647.0);
CREATE TABLE items (id bigserial PRIMARY KEY, v vector(${DIM}), tv turbovec.vector);
INSERT INTO items (v)
SELECT ARRAY(SELECT random_normal()::real FROM generate_series(1, ${DIM}))::vector
FROM generate_series(1, ${N_ROWS});
-- Backfill the native turbovec.vector column once (turbovec normalizes internally).
UPDATE items SET tv = v::real[]::turbovec.vector;
SQL
echo "[data] $($PSQL -c "SELECT count(*) FROM items;") rows loaded."

# 100 fixed query vectors, materialized in BOTH representations so each arm can
# feed its own operator the matching type. Reused across all regimes/engines.
$PSQL <<SQL
SELECT setseed((${SEED}+1) / 2147483647.0);
CREATE TABLE queries (qid int PRIMARY KEY, q vector(${DIM}), tq turbovec.vector);
INSERT INTO queries (qid, q)
SELECT g, ARRAY(SELECT random_normal()::real FROM generate_series(1, ${DIM}))::vector
FROM generate_series(1, 100) g;
UPDATE queries SET tq = q::real[]::turbovec.vector;
SQL

# ---------------------------------------------------------------------------
# Build indexes on their OWN columns. Both rank by cosine. Time each build
# (reported, not part of the latency CSV).
# ---------------------------------------------------------------------------
echo "[build] pg_turbovec ${BIT_WIDTH}-bit flat index (tv turbovec.vec_cosine_ops)..."
t0=$(date +%s.%N)
$PSQL -c "CREATE INDEX ${TV_INDEX} ON items USING turbovec (tv turbovec.vec_cosine_ops) WITH (bit_width = ${BIT_WIDTH});"
t1=$(date +%s.%N)
echo "[build] turbovec build: $(echo "$t1 - $t0" | bc)s"

echo "[build] pgvector HNSW index (v vector_cosine_ops, m=${HNSW_M}, ef_construction=${HNSW_EF_CONSTRUCTION})..."
t0=$(date +%s.%N)
$PSQL -c "CREATE INDEX ${HNSW_INDEX} ON items USING hnsw (v vector_cosine_ops) WITH (m = ${HNSW_M}, ef_construction = ${HNSW_EF_CONSTRUCTION});"
t1=$(date +%s.%N)
echo "[build] hnsw build: $(echo "$t1 - $t0" | bc)s"

$PSQL -c "SELECT pg_size_pretty(pg_relation_size('${TV_INDEX}')) AS turbovec_size, pg_size_pretty(pg_relation_size('${HNSW_INDEX}')) AS hnsw_size;"

# ---------------------------------------------------------------------------
# Measurement helpers.
#
# Each engine queries ITS OWN column with ITS OWN operator so the planner MUST
# route to the matching index:
#   hnsw : v  <=>                     (SELECT q  ...)   -> pgvector cosine
#   tv   : tv OPERATOR(turbovec.<=>)  (SELECT tq ...)   -> turbovec cosine (explicit binding
#          so it is NEVER pgvector's <=>)
# We read EXPLAIN ANALYZE's "Execution Time" (excludes psql round-trip), disable JIT
# (its warm-up would pollute the first query), and force enable_seqscan=off so the planner
# cannot fall back to a seqscan. We ALSO assert the plan used the intended index — a
# mis-planned query would otherwise silently report seqscan latency.
# ---------------------------------------------------------------------------

# Emit the SQL for one engine's query. $1=engine(tv|hnsw) $2=qid
query_sql() {
  local engine="$1" qid="$2"
  if [ "$engine" = "hnsw" ]; then
    printf 'SELECT id FROM items ORDER BY v <=> (SELECT q FROM queries WHERE qid = %s) LIMIT %s;' "$qid" "$K"
  else
    printf 'SELECT id FROM items ORDER BY tv OPERATOR(turbovec.<=>) (SELECT tq FROM queries WHERE qid = %s) LIMIT %s;' "$qid" "$K"
  fi
}

# Per-engine session setup (no turbovec.enabled toggle anymore).
session_setup() {
  local engine="$1"
  if [ "$engine" = "hnsw" ]; then
    printf 'SET hnsw.ef_search = %s; SET enable_indexscan = on; SET enable_seqscan = off; SET jit = off;' "$HNSW_EF_SEARCH"
  else
    printf 'SET enable_indexscan = on; SET enable_seqscan = off; SET jit = off;'
  fi
}

# The index name each engine's plan MUST reference.
expected_index() {
  [ "$1" = "hnsw" ] && echo "$HNSW_INDEX" || echo "$TV_INDEX"
}

# Run one query in a FRESH backend. Prints "<ms>" on success, or "SEQSCAN" if the
# plan did not use the intended index (trial should be flagged, not trusted).
run_one_query() {   # $1=engine(tv|hnsw) $2=qid
  local engine="$1" qid="$2"
  local want; want="$(expected_index "$engine")"
  local plan
  plan=$($PSQL <<SQL
$(session_setup "$engine")
EXPLAIN (ANALYZE, TIMING OFF, SUMMARY ON)
$(query_sql "$engine" "$qid")
SQL
)
  if ! grep -q "Index Scan using ${want}\|Index Only Scan using ${want}\|Bitmap Index Scan on ${want}\| using ${want}\|Index Cond.*${want}" <<<"$plan" \
     && ! grep -qi "${want}" <<<"$plan"; then
    echo "SEQSCAN"
    return 0
  fi
  grep -oP 'Execution Time: \K[0-9.]+' <<<"$plan" | head -n1
}

# Run TWO queries in ONE backend (same psql session). Prints "cold_ms warm_ms",
# or substitutes SEQSCAN for a value whose plan missed the index.
run_warm_pair() {   # $1=engine  -> prints "cold_ms warm_ms"
  local engine="$1"
  local want; want="$(expected_index "$engine")"
  local out
  out=$($PSQL <<SQL
$(session_setup "$engine")
EXPLAIN (ANALYZE, TIMING OFF, SUMMARY ON) $(query_sql "$engine" 1)
EXPLAIN (ANALYZE, TIMING OFF, SUMMARY ON) $(query_sql "$engine" 1)
SQL
)
  # Split the two EXPLAIN blocks on the "QUERY PLAN"-less boundary: each block
  # ends at its "Execution Time" line. Count index hits and pull both times.
  local hits times
  hits=$(grep -ci "${want}" <<<"$out" || true)
  times=$(grep -oP 'Execution Time: \K[0-9.]+' <<<"$out" | paste -sd' ')
  local cold warm
  cold=$(awk '{print $1}' <<<"$times"); warm=$(awk '{print $2}' <<<"$times")
  # Need the index referenced in BOTH plans (>=2 mentions); else flag both.
  if [ "${hits:-0}" -lt 2 ]; then
    echo "SEQSCAN SEQSCAN"
  else
    echo "${cold:-SEQSCAN} ${warm:-SEQSCAN}"
  fi
}

drop_os_cache() {
  # drop_caches only evicts the OS page cache, not shared_buffers. A *true* cold
  # measurement also wants shared_buffers cold — R1 restarts PG for that (see loop).
  sync
  sudo sh -c 'echo 3 > /proc/sys/vm/drop_caches'
}

# ---------------------------------------------------------------------------
# CSV header
# ---------------------------------------------------------------------------
echo "engine,regime,trial,latency_ms" > "$OUT"

emit() { echo "$1,$2,$3,$4" >> "$OUT"; }

SEQSCAN_FLAGS=0
note_seqscan() {   # $1=engine $2=regime $3=trial
  SEQSCAN_FLAGS=$((SEQSCAN_FLAGS + 1))
  echo "[WARN] $1/$2 trial $3: plan did NOT use $(expected_index "$1") — flagged, not recorded." >&2
}

# ---------------------------------------------------------------------------
# R3 warm-backend (lower bound). Take the SECOND query of a fresh-backend pair.
# ---------------------------------------------------------------------------
echo "[R3] warm-backend (2nd query, same backend)..."
for eng in tv hnsw; do
  for t in $(seq 1 "$TRIALS"); do
    pair=$(run_warm_pair "$eng")
    warm_ms=$(awk '{print $2}' <<<"$pair")
    if [ "$warm_ms" = "SEQSCAN" ]; then
      note_seqscan "$eng" "warm_backend" "$t"
    else
      emit "$eng" "warm_backend" "$t" "$warm_ms"
    fi
  done
done

# ---------------------------------------------------------------------------
# R2 cold-backend + warm-OS-cache (THE POOLED REALITY). Fresh backend each trial,
# NO drop_caches. Pages hot in OS cache/shared_buffers; only the per-backend
# cache-fill (read_chain copy + pack::repack) is paid.
# ---------------------------------------------------------------------------
echo "[R2] cold-backend + warm-OS-cache (pooled reality)..."
# Prewarm both indexes into shared_buffers + OS cache first (one throwaway backend each),
# so R2 genuinely reflects "pages resident, backend fresh".
$PSQL -c "SET enable_seqscan=off; $(query_sql tv 1)" >/dev/null
$PSQL -c "SET enable_seqscan=off; SET hnsw.ef_search=${HNSW_EF_SEARCH}; $(query_sql hnsw 1)" >/dev/null
for eng in tv hnsw; do
  for t in $(seq 1 "$TRIALS"); do
    qid=$(( (t % 100) + 1 ))
    ms=$(run_one_query "$eng" "$qid")   # fresh backend (new psql), no cache drop
    if [ "$ms" = "SEQSCAN" ]; then
      note_seqscan "$eng" "cold_backend_warm_os" "$t"
    else
      emit "$eng" "cold_backend_warm_os" "$t" "$ms"
    fi
  done
done

# ---------------------------------------------------------------------------
# R1 cold-backend + true-cold-disk (upper bound). drop_caches AND restart PG
# between trials so both OS page cache and shared_buffers are cold. Slowest;
# fewer trials to keep runtime sane.
# ---------------------------------------------------------------------------
if [ "$CAN_DROP_CACHES" -eq 1 ]; then
  echo "[R1] cold-backend + true-cold-disk (drop_caches + PG restart per trial)..."
  R1_TRIALS=$(( TRIALS < 10 ? TRIALS : 10 ))
  # pg_ctl path: honor PG_RESTART if set, else assume the Ubuntu package layout.
  PG_RESTART="${PG_RESTART:-sudo systemctl restart postgresql}"
  for eng in tv hnsw; do
    for t in $(seq 1 "$R1_TRIALS"); do
      # Cold shared_buffers: restart PG (NEVER kill -9 — AGENTS.md: crash recovery
      # truncates UNLOGGED tables; use a clean restart). Then cold OS cache.
      eval "$PG_RESTART" || { echo "[R1] restart failed; falling back to drop_caches only"; }
      sleep 3
      drop_os_cache
      qid=$(( (t % 100) + 1 ))
      ms=$(run_one_query "$eng" "$qid")
      if [ "$ms" = "SEQSCAN" ]; then
        note_seqscan "$eng" "cold_backend_cold_disk" "$t"
      else
        emit "$eng" "cold_backend_cold_disk" "$t" "$ms"
      fi
    done
  done
else
  echo "[R1] SKIPPED (no drop_caches privilege)."
fi

# ---------------------------------------------------------------------------
# Summary: p50/p95 per (engine, regime). Awk percentile on the CSV.
# ---------------------------------------------------------------------------
echo
echo "=== SUMMARY (p50 / p95 latency in ms) ==="
awk -F, 'NR>1 {
  key=$1" "$2; vals[key]=vals[key] $4 " ";
}
END {
  printf "%-10s %-26s %8s %8s %6s\n", "engine","regime","p50_ms","p95_ms","n";
  for (k in vals) {
    n=split(vals[k], a, " ");
    m=0; for(i=1;i<n;i++){ if(a[i]!=""){ arr[++m]=a[i]+0 } }
    if(m==0) continue;
    for(i=1;i<=m;i++) for(j=i+1;j<=m;j++) if(arr[j]<arr[i]){t=arr[i];arr[i]=arr[j];arr[j]=t}
    p50=arr[int((m-1)*0.50)+1]; p95=arr[int((m-1)*0.95)+1];
    split(k, kk, " ");
    printf "%-10s %-26s %8.1f %8.1f %6d\n", kk[1], kk[2], p50, p95, m;
    delete arr;
  }
}' "$OUT" | sort -k1,2

echo
[ "$SEQSCAN_FLAGS" -gt 0 ] && echo "!!! $SEQSCAN_FLAGS trial(s) FELL BACK TO SEQSCAN and were dropped — investigate the plan/opclass before trusting the table above."
echo "CSV: $OUT"
cat <<'EOF'

=== HOW TO READ THIS (the decision the design memo is gated on) ===
  R1 (cold_backend_cold_disk) - R2 (cold_backend_warm_os)  = DISK term.
      mmap-relevant, but mmap was deleted in v1.19.0 and is off the table.
  R2 (cold_backend_warm_os)  - R3 (warm_backend)            = PER-BACKEND COMPUTE term
      (read_chain copy + pack::repack). This is what §3a (parallel repack) could attack.

  If turbovec R2 ~= R3  -> cold penalty is disk-only; NOTHING scan-side helps. Report & stop.
  If turbovec R2 >> R3  -> repack/copy dominates; §3a (S, additive) is worth coding.
  Compare turbovec R2 vs hnsw R2 for the real pooled parity gap (the ~1.2s vs ~100ms line).

  BOTH engines rank by COSINE (hnsw vector_cosine_ops / turbovec OPERATOR(turbovec.<=>));
  the tv arm queries the turbovec.vector column, the hnsw arm the pgvector column — engine
  selection is by column+operator, and every trial asserts its index was actually used.
EOF
